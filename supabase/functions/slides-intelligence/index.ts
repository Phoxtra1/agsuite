// Slides intelligence edge function.
// Uses Lovable AI Gateway (LOVABLE_API_KEY) to generate slide content JSON.
// verify_jwt is intentionally left as default (true) — this is a signed-in feature.

// deno-lint-ignore-file no-explicit-any
import "https://deno.land/x/xhr@0.1.0/mod.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
};

type SlideElement = {
  id: string; kind: "text" | "shape" | "image";
  x: number; y: number; w: number; h: number;
  text?: string; fontSize?: number; fontWeight?: number; color?: string; align?: "left" | "center" | "right";
  shape?: "rect" | "ellipse"; fill?: string;
};
type Slide = { id: string; layout: string; background: string; elements: SlideElement[]; notes?: string };

function id() { return "s" + Math.random().toString(36).slice(2, 10); }

function makeFallbackDeck(prompt: string, theme: any): Slide[] {
  const primary = theme?.primary || "#1E2761";
  const accent = theme?.accent || "#2563eb";
  const bg = theme?.background || "#ffffff";
  return [
    { id: id(), layout: "title", background: bg, elements: [
      { id: id(), kind: "text", x: 160, y: 380, w: 1600, h: 200, text: prompt.slice(0, 80) || "Untitled", fontSize: 96, fontWeight: 800, color: primary, align: "center" },
      { id: id(), kind: "text", x: 160, y: 600, w: 1600, h: 80, text: "Generated by Amineva AI", fontSize: 32, color: accent, align: "center" },
    ] },
    { id: id(), layout: "titleContent", background: bg, elements: [
      { id: id(), kind: "text", x: 120, y: 90, w: 1680, h: 130, text: "Overview", fontSize: 72, fontWeight: 700, color: primary },
      { id: id(), kind: "text", x: 120, y: 260, w: 1680, h: 720, text: "• Key point derived from prompt\n• Supporting insight\n• Recommended next steps", fontSize: 36, color: "#0f172a" },
    ] },
  ];
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });
  try {
    const { action, prompt, theme } = await req.json();
    if (action !== "generate_deck" || !prompt) {
      return new Response(JSON.stringify({ error: "Invalid request" }), { status: 400, headers: { ...corsHeaders, "Content-Type": "application/json" } });
    }
    const apiKey = Deno.env.get("LOVABLE_API_KEY");
    if (!apiKey) {
      return new Response(JSON.stringify({ slides: makeFallbackDeck(prompt, theme), fallback: true }), { headers: { ...corsHeaders, "Content-Type": "application/json" } });
    }

    const sys = `You are Amineva AI, a presentation designer. Return STRICT JSON matching this schema:
{"slides":[{"layout":"title|titleContent|twoColumn|sectionHeader|quote","background":"#hex","elements":[{"kind":"text","x":number,"y":number,"w":number,"h":number,"text":"string","fontSize":number,"fontWeight":number,"color":"#hex","align":"left|center|right"}]}]}
Canvas is 1920x1080. Titles use fontSize 60-96 fontWeight 700-800. Body uses fontSize 28-40. Keep 4-8 slides. Do not include markdown. Only JSON.`;
    const user = `Theme: ${JSON.stringify(theme)}\nTopic / content:\n${prompt}\n\nReturn the JSON object only.`;

    const resp = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: { "Authorization": `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        model: "google/gemini-2.5-flash",
        messages: [{ role: "system", content: sys }, { role: "user", content: user }],
        response_format: { type: "json_object" },
      }),
    });
    if (!resp.ok) {
      const t = await resp.text();
      console.error("[slides-intelligence] gateway error", resp.status, t);
      return new Response(JSON.stringify({ slides: makeFallbackDeck(prompt, theme), fallback: true }), { headers: { ...corsHeaders, "Content-Type": "application/json" } });
    }
    const data = await resp.json();
    const raw = data?.choices?.[0]?.message?.content ?? "{}";
    let parsed: any = {};
    try { parsed = JSON.parse(raw); } catch { parsed = {}; }
    const slides: Slide[] = Array.isArray(parsed?.slides)
      ? parsed.slides.map((s: any) => ({
          id: id(),
          layout: s.layout || "titleContent",
          background: s.background || theme?.background || "#ffffff",
          elements: Array.isArray(s.elements) ? s.elements.map((e: any) => ({ ...e, id: id() })) : [],
          notes: s.notes || "",
        }))
      : makeFallbackDeck(prompt, theme);

    return new Response(JSON.stringify({ slides }), { headers: { ...corsHeaders, "Content-Type": "application/json" } });
  } catch (e) {
    console.error("[slides-intelligence] error", e);
    return new Response(JSON.stringify({ error: String((e as any)?.message || e) }), { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } });
  }
});
